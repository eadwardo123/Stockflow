-- Financial journal: one manually entered row per business journal entry.
CREATE TABLE IF NOT EXISTS financial_journal (
    id                         BIGINT AUTO_INCREMENT PRIMARY KEY,
    order_date                 DATE NOT NULL,
    `number`                   VARCHAR(100) NOT NULL,
    `type`                     VARCHAR(100) NOT NULL,
    name                       VARCHAR(255) NOT NULL,
    quantity_kg                DECIMAL(15,3) NOT NULL DEFAULT 0,
    stock_remaining            DECIMAL(15,3) NOT NULL DEFAULT 0,
    brand                      VARCHAR(255),
    serial_number              VARCHAR(255),
    adjustment                 DECIMAL(15,3) NOT NULL DEFAULT 0,
    purchase_price_per_unit    DECIMAL(15,4) NOT NULL DEFAULT 0,
    total_purchase_price       DECIMAL(15,4) NOT NULL DEFAULT 0,
    purchase_settlement_date   DATE,
    purchase_due_date          DATE,
    remaining_debt             DECIMAL(15,4) NOT NULL DEFAULT 0,
    selling_price_per_unit     DECIMAL(15,4) NOT NULL DEFAULT 0,
    total_selling_price        DECIMAL(15,4) NOT NULL DEFAULT 0,
    sale_settlement_date       DATE,
    sale_due_date              DATE,
    payment_status             VARCHAR(50),
    remaining_receivables      DECIMAL(15,4) NOT NULL DEFAULT 0,
    paid_status                VARCHAR(50),
    commission                 DECIMAL(15,4) NOT NULL DEFAULT 0,
    paid_commission            DECIMAL(15,4) NOT NULL DEFAULT 0,
    profit                     DECIMAL(15,4) NOT NULL DEFAULT 0,
    paid_to                    VARCHAR(255),
    notes                      TEXT,
    created_at                 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_financial_journal_order_date (order_date),
    INDEX idx_financial_journal_number (`number`)
);
